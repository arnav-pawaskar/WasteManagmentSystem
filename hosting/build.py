#!/usr/bin/env python3
"""
Build the read-only cloud dashboard for Firebase Hosting.

Copies the dashboard (web/templates/index.html + web/static/*) into
hosting/public/ and writes static/config.js so the page reads the snapshot the
fog layer publishes to Supabase, instead of the local FastAPI /api/* endpoints.

Reads SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY from the environment or .env.
The publishable (anon) key is public by design - Row Level Security makes it
read-only. The script refuses secret / service_role keys so they can never be
shipped to the browser.

    python hosting/build.py
    npx firebase-tools deploy --only hosting --project <your-firebase-project-id>
"""

import base64
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "hosting" / "public"


def load_env_file(path: Path):
    """Minimal .env reader (KEY=VALUE lines). Real environment variables win."""
    if not path.is_file():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def jwt_role(key: str):
    """Role claim of a legacy Supabase JWT key, or None if the key isn't a JWT."""
    parts = key.split(".")
    if len(parts) != 3:
        return None
    try:
        padded = parts[1] + "=" * (-len(parts[1]) % 4)
        return json.loads(base64.urlsafe_b64decode(padded)).get("role")
    except (ValueError, json.JSONDecodeError):
        return None


def check_public_key(key: str) -> str:
    """Return an error message if `key` must not be shipped to browsers."""
    if not key:
        return "SUPABASE_PUBLISHABLE_KEY is not set"
    if key.startswith("sb_secret_"):
        return "SUPABASE_PUBLISHABLE_KEY is a SECRET key (sb_secret_...). Use the publishable key."
    if jwt_role(key) == "service_role":
        return "SUPABASE_PUBLISHABLE_KEY is the service_role key. Use the anon/publishable key."
    return ""


def build(url: str, key: str, poll_ms: int = 3000) -> Path:
    if not url:
        raise ValueError("SUPABASE_URL is not set (add it to .env - see .env.example)")
    if not url.startswith("https://"):
        raise ValueError("SUPABASE_URL must start with https://")
    problem = check_public_key(key)
    if problem:
        raise ValueError(problem)

    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "static").mkdir(parents=True)

    shutil.copy2(WEB / "templates" / "index.html", OUT / "index.html")
    for asset in (WEB / "static").iterdir():
        if asset.is_file() and asset.name != "config.js":
            shutil.copy2(asset, OUT / "static" / asset.name)

    url = url.rstrip("/")
    if url.endswith("/rest/v1"):          # tolerate the Data API URL from the dashboard
        url = url[: -len("/rest/v1")]
    config = {"mode": "cloud", "supabaseUrl": url, "supabaseKey": key, "pollMs": poll_ms}
    (OUT / "static" / "config.js").write_text(
        "// Generated by hosting/build.py - cloud (read-only) dashboard config.\n"
        f"window.WMS_CONFIG = {json.dumps(config, indent=2)};\n",
        encoding="utf-8",
    )
    return OUT


def main() -> int:
    load_env_file(ROOT / ".env")
    url = os.environ.get("SUPABASE_URL", "").strip()
    key = os.environ.get("SUPABASE_PUBLISHABLE_KEY", "").strip()
    try:
        out = build(url, key, int(os.environ.get("DASHBOARD_POLL_MS", "3000")))
    except ValueError as e:
        print(f"Build failed: {e}", file=sys.stderr)
        return 1
    files = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file())
    print(f"Built cloud dashboard in {out}:")
    for f in files:
        print(f"  {f}")
    print("\nDeploy with:\n  npx firebase-tools deploy --only hosting --project <your-firebase-project-id>")
    return 0


if __name__ == "__main__":
    sys.exit(main())
